def prompts():
    out = {}
    for k, (desc, bg) in CHARS.items():
        out[f"chr_{k}"] = f"{STYLE}\n\nCHARACTER: {desc}\n\n" + POSES.format(bg=bg)
    for k, (far, wall, floor) in SCENES.items():
        out[f"far_{k}"] = f"{STYLE}\n\n" + FAR.format(scene=far)
        out[f"near_{k}"] = f"{STYLE}\n\n" + NEAR.format(wall=wall, floor=floor)
    out["props"] = f"{STYLE}\n\n{PROPS}"
    return out


if __name__ == "__main__":
    ps = prompts()
    if len(sys.argv) > 1:
        sys.stdout.write(ps[sys.argv[1]]); sys.exit(0)
    d = Path(__file__).resolve().parents[1] / "prompts"
    for k, v in ps.items():
        (d / f"cel_{k}.txt").write_text(v + "\n", encoding="utf-8")
    print(f"wrote {len(ps)}: {', '.join(ps)}")
