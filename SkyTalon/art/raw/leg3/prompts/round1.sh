#!/usr/bin/env bash
# run from SkyTalon/. Leg three ("the outer giants", gdd/05 v13): four bosses, five mid-bosses (Phobos and Deimos
# are two) on one sheet, the new machines and Prometheus's chains and eagle on one sheet. Style: leg one's own boss sheets; concept: the
# reference demo's pictures (shmup-bosses-3phase/demo_assets_arc2), never copied.
set -u
DEST=art/raw/leg3; mkdir -p "$DEST"
LOGDIR="$(dirname "$0")/codex_leg3_round1_logs"; mkdir -p "$LOGDIR"
STYLE=art/raw/boss/big_oceanus.png
MIDSTYLE=art/raw/boss/mids.png
G="${SHMUP_PACK:?set SHMUP_PACK to the shmup-bosses-3phase folder}/demo_assets_arc3"
RULES='- 16-bit 街機射擊遊戲的像素畫（pixel art）。硬邊像素、有限色盤、深色描邊、左上受光右下陰影、清楚的面板線與鉚釘。不要平滑漸層、不要反鋸齒、不要光暈、不要景深。
- 正俯視（從正上方垂直往下看），左右對稱（除非下面另外說明）。筆觸、描邊粗細與細節密度對齊附圖一。附圖二只是造型概念參考，不要照抄它的輪廓或細節。
- 這是機械戰艦，不是人物也不是生物：不畫人臉、人體、人手、宗教符號。圖裡不要任何文字、字母、數字、記號、標籤、邊框。
- 背景整張是純色 #00ff00（純綠色，不是黑色、不是深色、不是漸層），沒有陰影、沒有地面、沒有光暈、沒有特效。'
