job boss4_janus "$STYLE" "$G/boss_08_janus.png" "$BOSS" "主體：雙面門神艦「雅努斯」。配色洋紅 #e879f9、青 #22d3ee、深紫 #2a1a3a、銀 #c8ccd8。左右對半配色：左半艦以青色為主，右半艦以洋紅為主。艦首左右各一具大型的面甲狀感測罩（機械面罩，只是幾何形的發光感測器陣列，不畫人臉、沒有眼睛鼻子嘴），左邊的朝左下、右邊的朝右下。艦首中央是一道拱門形的結構。核心是銀白色圓核，左半發青光、右半發洋紅光。" &
