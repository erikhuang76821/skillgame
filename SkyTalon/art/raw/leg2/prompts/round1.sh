- 正俯視（從正上方垂直往下看），左右對稱（除非下面另外說明）。筆觸、描邊粗細與細節密度對齊附圖一。附圖二只是造型概念參考，不要照抄它的輪廓或細節。
- 這是機械戰艦，不是人物也不是生物：不畫人臉、人體、人手、宗教符號。圖裡不要任何文字、字母、數字、記號、標籤、邊框。
- 背景整張是純色 #00ff00，沒有陰影、沒有地面、沒有光暈、沒有特效。'
