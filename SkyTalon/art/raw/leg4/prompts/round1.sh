LOGDIR="$(dirname "$0")/codex_leg4_round1_logs"; mkdir -p "$LOGDIR"
STYLE=art/raw/boss/big_oceanus.png
MIDSTYLE=art/raw/boss/mids.png
G="${SHMUP_PACK:?set SHMUP_PACK to the shmup-bosses-3phase folder}/demo_assets_arc4"
