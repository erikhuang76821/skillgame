#!/usr/bin/env bash
# run from SkyTalon/. Leg four ("the underworld's edge", gdd/05 v14): four bosses, four mid-bosses on one sheet, the new
# machines on one sheet, and the bosses' parts (Briareus's arm, Charon's boat, Styx's heel) on one sheet. Style: leg one's own boss sheets; concept: the
# reference demo's pictures (shmup-bosses-3phase/demo_assets_arc4), never copied.
set -u
