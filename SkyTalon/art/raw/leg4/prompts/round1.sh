- 背景整張是純色 #00ff00（純綠色，不是黑色、不是深色、不是漸層），沒有陰影、沒有地面、沒有光暈、沒有特效。'
BOSS='請生成一張圖片（直接用圖片生成工具產生，不要寫程式、不要存檔、不要解說）。

用途：縱向卷軸射擊遊戲的大頭目素材（以希臘神話的神為名的機械巨艦）。巨艦體積遠大於畫面，平常只有艦首那一段從畫面上緣伸進來、朝下攻擊。所以：
- 整艘艦是縱長的（長寬比約 1:2），艦首朝畫面下方。
- 下半段（艦首）集中核心、主砲與最有特色的造型；砲口與翼尖朝下。核心放在離艦首尖端約四分之一艦長的位置。
- 上半段（艦橋、引擎）平常在畫面外，可以畫得比較單純，但要是同一艘艦連續的結構。

共同規格：
'"$RULES"'

構圖：同一艘艦的三個損壞階段由左到右並排，同樣大小、頂端對齊、彼此不重疊、之間留空，三艘都完整入鏡。
- 左：外甲完整。
- 中：外掛裝甲被打掉，露出同色系的桁架骨架與管線，艦身有彈孔、焦痕與餘燼；輪廓與左邊一致。
- 右：只剩核心。只有核心本體與緊貼它的一小圈撕裂金屬（邊緣燒紅），沒有其他艦身；放在與左邊核心相同的高度。
圖片比例橫向 3:2。
'
job() {
  local name=$1 ref1=$2 ref2=$3 head=$4 body=$5 log="$LOGDIR/$1.log"
  printf '%s\n%s\n' "$head" "$body" | codex exec --skip-git-repo-check --sandbox read-only -i "$ref1" -i "$ref2" - > "$log" 2>&1
  local sid; sid=$(grep -m1 '^session id:' "$log" | awk '{print $3}')
  [ -z "$sid" ] && { echo "$name: no session id (see $log)"; return 1; }
  local n=0
  for src in "$HOME/.codex/generated_images/$sid"/*.png; do
    [ -e "$src" ] || continue
    n=$((n + 1)); cp "$src" "$DEST/$name$([ $n -gt 1 ] && echo _$n).png"
  done
  [ "$n" -eq 0 ] && { echo "$name: no PNG in session $sid"; return 1; }
  echo "$name: $n png"
}
