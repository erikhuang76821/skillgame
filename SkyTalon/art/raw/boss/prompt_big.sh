#!/usr/bin/env bash
# run from SkyTalon/. Second round: bosses as huge ships seen only in part (bow down, attacking), per the user's direction.
set -u
DEST=art/raw/boss; mkdir -p "$DEST"
LOGDIR="$(dirname "$0")/codex_boss_logs2"; mkdir -p "$LOGDIR"
REF1=art/raw/ship_heavy.jpg

COMMON='請生成一張圖片（直接用圖片生成工具產生，不要寫程式、不要存檔、不要解說）。

用途：縱向卷軸射擊遊戲的大頭目素材。這類遊戲的大頭目是巨艦，體積遠大於畫面，平常只有艦首那一段從畫面上緣伸進來、朝下攻擊，並以左右橫移為主；只有往前衝鋒時才會露出更多艦身。所以：
- 整艘艦是縱長的（長寬比約 1:2，高是寬的兩倍），艦首朝畫面下方。
- 下半段（艦首）是玩家平常看到的部分：核心、主砲、所有武裝與最有特色的造型元素都集中在這裡，砲口與爪、臂、翼尖一律朝下、往前伸，呈現正在往下攻擊的姿態。核心放在離艦首尖端約四分之一艦長的位置。
- 上半段（艦身中後段、艦橋、引擎）平常在畫面外，衝鋒時才露出，可以畫得比較單純，但要是同一艘艦連續的結構。

共同規格：
- 16-bit 街機射擊遊戲的像素畫（pixel art）。硬邊像素、有限色盤、深色描邊、左上受光右下陰影、清楚的面板線與鉚釘。不要平滑漸層、不要反鋸齒、不要光暈、不要景深。
- 正俯視（從正上方垂直往下看），左右對稱。筆觸與細節密度對齊附圖（玩家機的風格參考）。
- 這是機械戰艦，不是人物也不是生物：不畫人臉、人體、人手、宗教符號。圖裡不要任何文字、字母、數字、記號、標籤、邊框。
- 背景整張是純色 #00ff00，沒有陰影、沒有地面、沒有光暈、沒有特效。

構圖：同一艘艦的三個損壞階段由左到右並排，同樣大小、頂端對齊、彼此不重疊、之間留空，三艘都完整入鏡。
- 左：外甲完整。
- 中：外掛裝甲被打掉，露出同色系的桁架骨架與管線，艦身有彈孔、焦痕與餘燼；輪廓與左邊一致。
- 右：只剩核心。只有核心本體與緊貼它的一小圈撕裂金屬（邊緣燒紅），沒有其他艦身；放在與左邊核心相同的高度。
圖片比例橫向 3:2。
'
job() {
  local name=$1 body=$2 log="$LOGDIR/$1.log"
  printf '%s\n%s\n' "$COMMON" "$body" | codex exec --skip-git-repo-check --sandbox read-only -i "$REF1" - > "$log" 2>&1
  local sid; sid=$(grep -m1 '^session id:' "$log" | awk '{print $3}')
  [ -z "$sid" ] && { echo "$name: no session id (see $log)"; return 1; }
  local n=0
  for src in "$HOME/.codex/generated_images/$sid"/*.png; do
    [ -e "$src" ] || continue
    n=$((n + 1)); cp "$src" "$DEST/$name$([ $n -gt 1 ] && echo _$n).png"
  done
  [ "$n" -eq 0 ] && { echo "$name: no PNG in session $sid"; return 1; }
  echo "$name: $n png"
}
job big_oceanus "主體：海神艦「俄刻阿諾斯」。配色深海藍 #1c4a6e、海藍 #2f7aa8、淺藍 #7fc8e0、浪白 #d8f4f4、金 #ffd24a。艦首兩側一對巨大的機械蟹螯往下張開，螯之間是多管主砲；兩舷是浪花捲形的裝甲鰭，鰭緣一道白浪；艦尾有一對角。核心是金色圓核，外面一圈水環。" &
job big_nyx "主體：夜之艦「倪克斯」。配色夜黑紫 #1e1a40、靛 #3a3478、紫 #6a5fc0、星白 #f4f0c8。兩片垂墜的星幕裝甲大翼像披風一樣往下垂到艦首兩側，上面有星點與摺線，翼尖朝下；翼下藏著朝下的砲管。核心是艦首上一彎發亮的新月，下方一顆青色燈。" &
job big_eos "主體：黎明之艦「厄俄斯」。配色玫瑰 #e8829a、深玫瑰 #b85478、番紅花橙 #ffb85a、奶油 #ffe9c0、暮紫 #7a6ac0。艦首兩側各五道玫瑰色與橙色相間的光芒形裝甲板，像扇子一樣往斜下方展開；艦身是古代戰車的車身，兩條護欄往艦首延伸成砲管。核心是一個奶油色的戰車車輪（輪圈與十字輪輻），輪心發亮。" &
job big_atlas "主體：扛天之艦「阿特拉斯」。配色青銅 #8a5a3a、亮銅 #c98a52、石灰藍 #5a5f78、深空藍 #1e2a5a、星白 #fff1c9。艦首是一顆巨大的天球儀（深藍球面、經線緯線、星點、銅色外環），由兩支青銅色的機械起重臂（工業桁架與液壓缸，不是人的手臂，沒有手指）從兩側夾住往前推；起重臂外側是朝下的砲塔。核心就是天球。" &
wait
ls "$DEST"
