"""Turns the reference pictures of the ship's forms (art/raw/ship_*.jpg, generated with Gemini and supplied by the
user) into pixel sprites the game draws: finds the size of one art pixel, takes one colour per art pixel, removes
the flat background, reduces everything to one shared palette and writes
  game/src/render/shipForms.js   palette + rows of palette indices (the game ships no image file)
  art/preview/v8_ship_forms.png  the result enlarged, for review
Mechanical only, no hand edits. Run from SkyTalon/:  python art/tools/ship_forms.py
"""
import json
import numpy as np
from PIL import Image

FORMS = [("wing", "art/raw/ship_wing.jpg"), ("heavy", "art/raw/ship_heavy.jpg"), ("rail", "art/raw/ship_rail.jpg")]
COLOURS = 40


def block_size(a):
    """The art-pixel size: the candidate whose grid lines carry the most colour change."""
    g = a.astype(np.int32)
    dx = np.abs(np.diff(g, axis=1)).sum(axis=(0, 2))
    best, score = 16, -1
    for n in np.arange(7.0, 12.01, 0.02):
        for off in np.arange(0, n, 0.5):
            idx = np.round(np.arange(off, len(dx), n)).astype(int)
            idx = idx[idx < len(dx)]
            s = dx[idx].mean() / (dx.mean() + 1)
            if s > score:
                best, score, boff = n, s, off
    return best, boff


def to_pixels(path):
    a = np.asarray(Image.open(path).convert("RGB"))
    n, off = block_size(a)
    bg = np.median(a[:24, :24].reshape(-1, 3), axis=0)
    xs = np.arange(off, a.shape[1] - n / 2, n)
    ys = np.arange(off, a.shape[0] - n / 2, n)
    out = np.zeros((len(ys), len(xs), 4), np.uint8)
    for j, y in enumerate(ys):
        for i, x in enumerate(xs):
            y0, y1, x0, x1 = int(y + n * 0.3), int(y + n * 0.7) + 1, int(x + n * 0.3), int(x + n * 0.7) + 1
            c = np.median(a[y0:y1, x0:x1].reshape(-1, 3), axis=0)
            keep = np.abs(c - bg).sum() > 46
            out[j, i] = (*c.astype(np.uint8), 255 if keep else 0)
    ys_, xs_ = np.nonzero(out[..., 3])
    return out[ys_.min():ys_.max() + 1, xs_.min():xs_.max() + 1], n


def main():
    sprites = [(name, *to_pixels(path)) for name, path in FORMS]
    # one palette for all forms
    stack = np.concatenate([s[..., :3][s[..., 3] > 0] for _, s, _ in sprites])
    pal_img = Image.fromarray(stack.reshape(1, -1, 3), "RGB").quantize(COLOURS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = np.array(pal_img.getpalette()[:COLOURS * 3]).reshape(-1, 3)
    forms = {}
    for name, s, n in sprites:
        rgb = s[..., :3].astype(np.int32)
        idx = np.argmin(((rgb[:, :, None, :] - pal[None, None, :, :]) ** 2).sum(-1), axis=-1)
        rows = ["".join("." if s[y, x, 3] == 0 else chr(48 + int(idx[y, x])) for x in range(s.shape[1])) for y in range(s.shape[0])]
        forms[name] = rows
        print(f"{name}: art pixel {n} px, sprite {s.shape[1]}x{s.shape[0]}")
    js = "// GENERATED by art/tools/ship_forms.py from art/raw/ship_*.jpg (reference pictures supplied by the user). Do not edit.\n"
    js += "// One character per art pixel: '.' = empty, chr(48 + n) = palette index n.\n"
    js += "export const SHIP_PALETTE = " + json.dumps([int(r) << 16 | int(g) << 8 | int(b) for r, g, b in pal]) + ";\n"
    js += "export const SHIP_FORMS = " + json.dumps(forms, indent=1) + ";\n"
    open("game/src/render/shipForms.js", "w", encoding="utf-8", newline="\n").write(js)
    # preview
    K, pad = 8, 16
    W = sum(len(r[0]) for r in forms.values()) * K + pad * (len(forms) + 1)
    H = max(len(r) for r in forms.values()) * K + pad * 2
    img = Image.new("RGB", (W, H), (58, 106, 122))
    x0 = pad
    for name, rows in forms.items():
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != ".":
                    c = tuple(int(v) for v in pal[ord(ch) - 48])
                    img.paste(c, (x0 + x * K, pad + y * K, x0 + x * K + K, pad + y * K + K))
        x0 += len(rows[0]) * K + pad
    img.save("art/preview/v8_ship_forms.png")


main()
